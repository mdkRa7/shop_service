import uuid
from typing import Any, Protocol


class Repository[EntityT](Protocol):
    """Port that use cases depend on. Infrastructure implements it."""

    async def get(self, obj_id: uuid.UUID) -> EntityT | None: ...

    async def get_or_raise(self, obj_id: uuid.UUID) -> EntityT: ...

    async def create(self, data: dict[str, Any]) -> EntityT: ...

    async def update(self, obj: EntityT, data: dict[str, Any]) -> EntityT: ...

    async def delete(self, obj: EntityT) -> None: ...
