import uuid
from typing import Any, Protocol, Sequence


class RecipeRepositoryProtocol(Protocol):
    async def get_all(self, *where: Any, order_by: Sequence[Any] = ()): ...
    async def get_all_active(self): ...
    async def get_active_by_id(self, obj_id: uuid.UUID): ...
    async def get_or_raise(self, obj_id: uuid.UUID): ...
    async def create(self, data: dict[str, Any]): ...
    async def update(self, obj, data: dict[str, Any]): ...
    async def delete(self, obj) -> None: ...
